import assert from 'node:assert/strict';
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createActorPuppetPresentation } from '../../../web-runner/systems/actorPuppetPresentation.mjs';
const semanticResetCheckpoint = '5d674b0c76d40305dc6c0317dbcf8e53606c3784';
const source = execFileSync('git', ['show', `${semanticResetCheckpoint}:web-runner/src/core/actorPresentationState.mjs`], { encoding: 'utf8' });
const { resetActorPresentationAfterRestore } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
let releaseIdle;
const koClip = { frames: [{ name: 'ko' }], frameHoldMs: [1000], durationMs: 1000, loop: false };
const idleClip = { ...koClip, frames: [{ name: 'idle' }], loop: true };
const presentation = createActorPuppetPresentation({ loadClip: (_actor, state) => state === 'ko' ? Promise.resolve(koClip) : new Promise(resolve => { releaseIdle = resolve; }) });
const hero = { uid: 1, name: 'Fara', hp: 0, facing: 'right', actionState: 'ko', actionStateStartedAt: 1, actionStateUntil: 100, actionFacing: 'right' };
presentation.frameFor(hero, 2);
await new Promise(resolve => setImmediate(resolve));
assert.equal(presentation.frameFor(hero, 2).state, 'ko');
hero.hp = 100;
resetActorPresentationAfterRestore(hero, 2);
assert.equal(hero.actionState, undefined);
assert.equal(hero.locomotion, 'idle');
assert.equal(presentation.frameFor(hero, 2), null, 'semantic reset must immediately stop displaying cached KO');
await new Promise(resolve => setImmediate(resolve));
releaseIdle(idleClip);
await new Promise(resolve => setImmediate(resolve));
assert.equal(presentation.frameFor(hero, 2).state, 'idle');
const result = { semanticResetCheckpoint, sameSimulationTime: 2, cachedKoBeforeRestore: true, coldIdleAfterRestoreReturnsNull: true, resolvedIdleAfterRestore: true, status: 'PASS' };
fs.writeFileSync(new URL('restore-boundary-proof.json', import.meta.url), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result));
